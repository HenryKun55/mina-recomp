"""Regenerates runtime/include/gl_null.h: every GL call and enum the Metal layer
uses, as no-ops (values from the macOS SDK's GL headers).

    python3 tools/gen_gl_null.py
"""
import glob
import os
import re
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SDK = subprocess.check_output(["xcrun", "--show-sdk-path"], text=True).strip()
H = SDK + "/System/Library/Frameworks/OpenGL.framework/Headers"
src = "".join(open(os.path.join(ROOT, "runtime/src", f)).read() for f in ("metal.c", "metal_enc.c"))
src = re.sub(r"#if defined\(__vita__\)\n#if !defined\(MINA_NULL_GL\).*?#endif\n", "", src, flags=re.S)
consts = sorted(set(re.findall(r"\bGL_[A-Z0-9_]+", src)))
defs = {}
for f in glob.glob(H + "/*.h"):
    for m in re.finditer(r"#define\s+(GL_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)", open(f).read()):
        defs.setdefault(m.group(1), m.group(2))
defs.update({"GL_COMPRESSED_RGBA_S3TC_DXT1_EXT": "0x83F1", "GL_COMPRESSED_RGBA_S3TC_DXT3_EXT": "0x83F2",
             "GL_COMPRESSED_RGBA_S3TC_DXT5_EXT": "0x83F3", "GL_COMPRESSED_RGBA_BPTC_UNORM": "0x8E8C"})
fns = sorted(set(re.findall(r"\b(gl[A-Z][A-Za-z0-9]+)\(", src)))
out = ["/* generated by tools/gen_gl_null.py */", "/*",
       " * A null OpenGL: every call the Metal layer makes does nothing (or answers",
       ' * "complete / compiled / linked"). Vita builds with MINA_VITA_NULL_GL run the',
       " * game logic with it, to measure CPU and memory without a renderer.", " */",
       "#ifndef MINA_GL_NULL_H", "#define MINA_GL_NULL_H", "", "#include <stdint.h>", "#include <stddef.h>", "",
       "typedef unsigned int GLenum, GLuint, GLbitfield;", "typedef int GLint, GLsizei;",
       "typedef unsigned char GLboolean;", "typedef float GLfloat;", "typedef double GLdouble;",
       "typedef char GLchar;", "typedef ptrdiff_t GLintptr, GLsizeiptr;", "#define GL_TRUE 1", "#define GL_FALSE 0", ""]
for c in consts:
    if c in ("GL_TRUE", "GL_FALSE"):
        continue
    if c not in defs:
        raise SystemExit("no value for " + c)
    out.append("#define %s %s" % (c, defs[c]))
out += ["", "static GLuint gl_null_next = 1;"]
special = {
    "glCreateProgram": "static inline GLuint glCreateProgram(void) { return gl_null_next++; }",
    "glCreateShader": "static inline GLuint glCreateShader(GLenum t) { (void)t; return gl_null_next++; }",
    "glCheckFramebufferStatus": "static inline GLenum glCheckFramebufferStatus(GLenum t) { (void)t; return GL_FRAMEBUFFER_COMPLETE; }",
    "glGetError": "static inline GLenum glGetError(void) { return 0; }",
    "glGetUniformLocation": "static inline GLint glGetUniformLocation(GLuint p, const GLchar *n) { (void)p; (void)n; return -1; }",
    "glGetProgramiv": "static inline void glGetProgramiv(GLuint p, GLenum e, GLint *v) { (void)p; (void)e; *v = 1; }",
    "glGetShaderiv": "static inline void glGetShaderiv(GLuint s, GLenum e, GLint *v) { (void)s; (void)e; *v = 1; }",
}
for f in fns:
    if f in special:
        out.append(special[f])
    elif f.startswith("glGen") and not f.startswith("glGenerate"):
        out.append("static inline void %s(GLsizei n, GLuint *ids) { for (GLsizei i = 0; i < n; i++) ids[i] = gl_null_next++; }" % f)
    else:
        out.append("#define %s(...) ((void)0)" % f)
out += ["", "#endif"]
open(os.path.join(ROOT, "runtime/include/gl_null.h"), "w").write("\n".join(out) + "\n")
print("%d constants, %d functions" % (len(consts), len(fns)))
